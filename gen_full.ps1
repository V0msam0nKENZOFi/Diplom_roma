function P($text, $size, $bold, $align) {
    $p = $doc.Paragraphs.Add()
    $p.Range.Text = $text
    $p.Range.Font.Name = "Times New Roman"
    $p.Range.Font.Size = $size
    $p.Range.Font.Bold = $bold
    $p.Alignment = $align
    $p.Range.ParagraphFormat.LineSpacingRule = 1.5
    return $p
}
