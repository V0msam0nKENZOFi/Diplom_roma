def norm(s: str) -> str:
    return re.sub(r"\s+", " ", s.strip().upper())


def set_paragraph_text(paragraph: Paragraph, text: str) -> None:
    if paragraph.runs:
        paragraph.runs[0].text = text
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(text)


def insert_paragraph_after(paragraph: Paragraph, text: str) -> Paragraph:
    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    new_para = Paragraph(new_p, paragraph._parent)
    new_para.add_run(text)
    return new_para


def clear_document_body(doc: Document) -> None:
    body = doc.element.body
    for child in list(body):
        tag = child.tag.split("}")[-1]
        if tag != "sectPr":
            body.remove(child)


def build_document_from_sections(doc: Document) -> None:
    clear_document_body(doc)
    for heading, paragraphs in SECTIONS:
        h = doc.add_heading(
            heading,
            level=1 if heading.startswith("ГЛАВА") or heading == "ЗАКЛЮЧЕНИЕ" else 2,
        )
        if not paragraphs:
            continue
        for text in paragraphs:
            p = doc.add_paragraph(text)
            p.paragraph_format.first_line_indent = None


def fill_into_existing_template(doc: Document) -> None:
    paragraphs = list(doc.paragraphs)
    section_map = {norm(k): v for k, v in SECTIONS}

    i = 0
    while i < len(paragraphs):
        title = norm(paragraphs[i].text)
        if title in section_map:
            lines = section_map[title]
            j = i + 1
            line_idx = 0
            while j < len(paragraphs) and line_idx < len(lines):
                next_title = norm(paragraphs[j].text)
                if next_title in section_map:
                    break
                if (
                    not paragraphs[j].text.strip()
                    or len(paragraphs[j].text.strip()) < 250
                    or paragraphs[j].text.strip().startswith("[")
                ):
                    set_paragraph_text(paragraphs[j], lines[line_idx])
                    line_idx += 1
                j += 1
            anchor = paragraphs[j - 1] if j > i + 1 else paragraphs[i]
            while line_idx < len(lines):
                new_p = insert_paragraph_after(anchor, lines[line_idx])
                paragraphs.insert(j, new_p)
                anchor = new_p
                j += 1
                line_idx += 1
            i = j
        else:
            i += 1

    if len([p for p in doc.paragraphs if len(p.text.strip()) > 20]) < 5:
        for heading, lines in SECTIONS:
            doc.add_heading(heading, level=1)
            for line in lines:
                doc.add_paragraph(line)


def ensure_source_file() -> None:
    if SRC.exists() and SRC.stat().st_size >= 100:
        return
    doc = Document()
    doc.add_paragraph(" ")
    doc.save(str(SRC))


def main() -> int:
    if not SRC.exists():
        ensure_source_file()

    if SRC.stat().st_size < 100:
        ensure_source_file()

    if not BACKUP.exists() and SRC.stat().st_size >= 100:
        shutil.copy2(SRC, BACKUP)

    doc = Document(str(SRC))
    plain_len = sum(len(p.text) for p in doc.paragraphs)

    if plain_len < 100:
        build_document_from_sections(doc)
    else:
        fill_into_existing_template(doc)

    doc.save(str(OUT))
    print(f"Готово: {OUT} ({OUT.stat().st_size} байт)")
    return 0


