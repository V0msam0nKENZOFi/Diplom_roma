function Add-Paragraph($text, $styleName, $fontSize, $bold, $alignment, $fontName) {
    $p = $doc.Paragraphs.Add()
    $p.Range.Text = $text
    $p.Style = $doc.Styles($styleName)
    $p.Range.Font.Name = if ($fontName) { $fontName } else { "Times New Roman" }
    $p.Range.Font.Size = $fontSize
    $p.Range.Font.Bold = $bold
    $p.Alignment = $alignment
    $p.Range.ParagraphFormat.LineSpacingRule = 1.5
    $p.Range.ParagraphFormat.SpaceBefore = 0
    $p.Range.ParagraphFormat.SpaceAfter = 0
    return $p
}

function Add-EmptyLine {
